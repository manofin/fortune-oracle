# ---------------------------------------------------------------------------
# 동류/이류 계산
# ---------------------------------------------------------------------------

def classify_dongryu_iryu(day_master_element: str) -> Dict[str, List[str]]:
    """동류/이류 계산.

    Returns:
        {
            "dongryu": [일간과 같은 오행],
            "sheng": [일간을 생하는 오행],
            "ke": [일간을 극하는 오행],
            "xie": [일간이 설기하는 오행],
        }
    """
    if not day_master_element:
        return {"dongryu": [], "sheng": [], "ke": [], "xie": []}

    dongryu = [day_master_element]

    # 생조 (일간을 생하는 오행)
    sheng = [e for e, t in SHENG.items() if t == day_master_element]

    # 극 (일간을 극하는 오행)
    ke = [e for e, t in KE.items() if t == day_master_element]

    # 설기 (일간이 설기하는 오행)
    xie = [SHENG[day_master_element]] if day_master_element in SHENG else []

    return {
        "dongryu": dongryu,
        "sheng": sheng,
        "ke": ke,
        "xie": xie,
    }

